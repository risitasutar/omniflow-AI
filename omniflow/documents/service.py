"""Document ingestion and retrieval for one app process.

ingest:  validate -> deduplicate (SHA-256) -> extract pages (bounded time) -> chunk ->
         embed locally -> add to the caller's session index
search:  embed query locally -> cosine top-k within that session only

Session ids are generated by the app, never taken from user or model input.
"""

from __future__ import annotations

import hashlib
import threading
import time
import uuid
from collections.abc import Callable
from concurrent.futures import ThreadPoolExecutor
from concurrent.futures import TimeoutError as FutureTimeout
from dataclasses import dataclass

from omniflow.core.config import Settings
from omniflow.core.logging_setup import get_logger, log_event
from omniflow.documents.chunking import chunk_pages
from omniflow.documents.embeddings import Embedder
from omniflow.documents.ocr import OcrEngine
from omniflow.documents.pdf import (
    DocumentError,
    extract_pdf,
    safe_display_name,
    validate_upload,
)
from omniflow.documents.store import DocumentRecord, DocumentStore, SearchHit

logger = get_logger("documents.service")
_POOL = ThreadPoolExecutor(max_workers=2, thread_name_prefix="omniflow-pdf")


@dataclass(frozen=True)
class IngestReport:
    filename: str
    status: str  # "indexed" | "duplicate" | "rejected"
    message: str
    record: DocumentRecord | None = None


class DocumentService:
    def __init__(
        self,
        settings: Settings,
        store: DocumentStore,
        embedder_factory: Callable[[], Embedder],
        ocr: OcrEngine | None = None,
    ) -> None:
        self.settings = settings
        self.store = store
        self.ocr = ocr
        self._embedder_factory = embedder_factory
        self._embedder: Embedder | None = None
        self._embedder_lock = threading.Lock()

    # ------------------------------------------------------------------ helpers
    @property
    def embedder(self) -> Embedder:
        with self._embedder_lock:
            if self._embedder is None:
                self._embedder = self._embedder_factory()
            return self._embedder

    @property
    def embedder_loaded(self) -> bool:
        return self._embedder is not None

    def documents(self, session_id: str | None) -> list[DocumentRecord]:
        index = self.store.get(session_id)
        if index is None:
            return []
        with self.store.lock:
            return list(index.documents.values())

    def has_documents(self, session_id: str | None) -> bool:
        return bool(self.documents(session_id))

    def remove(self, session_id: str | None, doc_id: str) -> bool:
        index = self.store.get(session_id)
        if index is None:
            return False
        with self.store.lock:
            return index.remove(doc_id)

    def clear(self, session_id: str | None) -> None:
        self.store.clear(session_id)

    # ------------------------------------------------------------------- ingest
    def ingest(
        self,
        session_id: str,
        filename: str | None,
        data: bytes,
        progress: Callable[[str], None] = lambda _msg: None,
    ) -> IngestReport:
        name = safe_display_name(filename)
        started = time.perf_counter()
        try:
            report = self._ingest(session_id, name, filename, data, progress)
        except DocumentError as exc:
            report = IngestReport(name, "rejected", exc.safe_message)
        except Exception:  # noqa: BLE001 - never surface internals; details go to the log
            logger.exception("Unexpected error while processing a PDF")
            report = IngestReport(name, "rejected", "The PDF could not be processed.")
        log_event(
            logger, "document_ingest", status=report.status, size_kb=len(data) // 1024,
            pages=report.record.page_count if report.record else None,
            chunks=report.record.chunk_count if report.record else None,
            duration_ms=round((time.perf_counter() - started) * 1000),
        )
        return report

    def _ingest(self, session_id, name, raw_name, data, progress) -> IngestReport:
        s = self.settings
        validate_upload(raw_name, data, int(s.rag_max_file_mb * 1_000_000))
        index = self.store.get(session_id, create=True)
        if index is None:
            raise DocumentError("invalid_session", "The document session is not valid.")

        sha256 = hashlib.sha256(data).hexdigest()
        with self.store.lock:
            existing = index.find_by_hash(sha256)
            if existing is not None:
                return IngestReport(
                    name, "duplicate",
                    f"Already indexed as '{existing.filename}' - skipped re-processing.", existing,
                )
            if len(index.documents) >= s.rag_max_files:
                raise DocumentError(
                    "too_many_files", f"The limit is {s.rag_max_files} documents per session."
                )

        progress("Extracting text…")
        future = _POOL.submit(
            extract_pdf, data, max_pages=s.rag_max_pages, max_chars=s.rag_max_chars_per_file,
            ocr=self.ocr, ocr_max_pages=s.ocr_max_pages,
        )
        try:
            extraction = future.result(timeout=s.rag_extract_timeout_seconds)
        except FutureTimeout as exc:
            raise DocumentError(
                "timeout", "Reading the PDF took too long; try a smaller file."
            ) from exc

        if not extraction.pages:
            if extraction.image_only_pages:
                hint = (" OCR is not available - install Tesseract to read scanned pages."
                        if self.ocr is None else " OCR could not read the scanned pages.")
                raise DocumentError(
                    "no_text", "The PDF appears to contain only scanned images, so no text "
                    "could be extracted." + hint,
                )
            raise DocumentError("no_text", "The PDF contains no extractable text.")

        doc_id = uuid.uuid4().hex
        chunks = chunk_pages(
            extraction.pages, doc_id=doc_id, filename=name,
            chunk_size=s.rag_chunk_size, overlap=s.rag_chunk_overlap,
        )
        with self.store.lock:
            if index.chunk_count + len(chunks) > s.rag_max_chunks:
                raise DocumentError(
                    "too_many_chunks",
                    f"Adding this file would exceed the {s.rag_max_chunks:,}-passage limit "
                    "for this session. Remove a document or upload a smaller file.",
                )

        progress(f"Embedding {len(chunks)} passages locally…")
        vectors = self.embedder.embed_documents([c.text for c in chunks])

        warnings = list(extraction.warnings)
        if extraction.image_only_pages:
            warnings.append(
                f"{len(extraction.image_only_pages)} page(s) contain only images and were not "
                "searchable" + (" (install Tesseract to enable OCR)." if self.ocr is None else ".")
            )
        record = DocumentRecord(
            doc_id=doc_id, filename=name, sha256=sha256, page_count=extraction.page_count,
            text_pages=len(extraction.pages), ocr_pages=extraction.ocr_pages,
            image_only_pages=extraction.image_only_pages, empty_pages=extraction.empty_pages,
            chunk_count=len(chunks), warnings=warnings,
        )
        with self.store.lock:
            if index.find_by_hash(sha256) is not None:  # a concurrent upload won the race
                return IngestReport(name, "duplicate", "Already indexed - skipped.", record)
            index.add(record, chunks, vectors)
        return IngestReport(
            name, "indexed",
            f"Indexed {len(chunks)} passages from {len(extraction.pages)} of "
            f"{extraction.page_count} pages.", record,
        )

    # ------------------------------------------------------------------- search
    def search(self, session_id: str | None, query: str, k: int) -> list[SearchHit]:
        index = self.store.get(session_id)
        if index is None or not index.documents:
            return []
        vector = self.embedder.embed_query(query)
        with self.store.lock:
            return index.search(vector, min(k, self.settings.rag_top_k),
                                self.settings.rag_min_score)
